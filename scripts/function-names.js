// Writes function-names.md from core as it is now, marking the names the
// baseline (0.6.6) core also defined. The file is generated whole and kept
// out of git, since every edit to core moves its line numbers. Usage:
// npm run docs:functions
import {readFile, readdir, writeFile} from 'node:fs/promises'
import path from 'node:path'
import {definitionsOf, functionIndex, isCore, renderIndex} from './lib/function-index.js'
import {baselineFiles, baselineSource} from './lib/baseline.js'

// What the tables mean, ahead of them.
const INTRODUCTION = `# MicroQL core — function names by file

Every named function in core: \`function\` declarations, \`const\` function values, object properties (util resources, store methods) and class methods. Anonymous inline callbacks are not listed.

- **lines** — length of the definition
- **refs** — identifiers naming the function in core: in its own file, plus in files that import it, leaving out its declaration, import and export lists, property keys and member names. 0 means public API used only by callers outside core (tests, hosts). Properties and methods are dispatched by name at run time, so they get no count. Names are matched textually, so a parameter that shadows a function is counted too.
- **0.6** — 0.6.6 core (\`836d9bf\`) also defined a function by this name

This file is generated by \`npm run docs:functions\`, and not committed: edit the introduction in \`scripts/function-names.js\`.`

// The core files of the working tree, with their sources, in path order.
async function currentSources() {
  const nested = (await readdir('src', {recursive: true})).map(file => path.join('src', file))
  const files = [...await readdir('.'), ...nested].filter(isCore).sort()
  return Object.fromEntries(await Promise.all(files.map(async file => [file, await readFile(file, 'utf8')])))
}

// The names 0.6.6 core defined.
const baselineNames = () =>
  new Set(baselineFiles().filter(isCore).flatMap(file => definitionsOf(baselineSource(file)).map(d => d.name)))

await writeFile('function-names.md', `${INTRODUCTION}\n\n${renderIndex(functionIndex(await currentSources(), baselineNames()))}\n`)
console.log('function-names.md: written')
